<?php

class UnidadeExtd {
    
    private $unidade = null;
    private $idUnidade = null;
    
    function getIdUnidade() {
        return $this->idUnidade;
    }

    function setIdUnidade($idUnidade) {
        $this->idUnidade = $idUnidade;
    }

    function getUnidade() {
        return $this->unidade;
    }

    function setUnidade($unidade) {
        $this->unidade = $unidade;
    }

}
    

